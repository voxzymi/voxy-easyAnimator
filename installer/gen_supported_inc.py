"""Turns supported_ae_versions.json into build/supported_ae.inc for the Inno Setup script (Pascal cannot read JSON easily)."""
import json
import os
import sys

root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
cfg = json.load(open(os.path.join(root, "installer", "supported_ae_versions.json"), encoding="utf-8"))
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "build", "supported_ae.inc")
os.makedirs(os.path.dirname(out), exist_ok=True)
lines = ["// generated by installer/gen_supported_inc.py: do not edit", f"#define AEConfirmed {'1' if cfg['confirmed'] else '0'}"]
lines.append(f"#define AECount {len(cfg['versions'])}")
for i, v in enumerate(cfg["versions"]):
    lines.append(f'#define AEName{i} "{v["name"]}"')
    lines.append(f'#define AEKey{i} "{v["registry_key"]}"')
    lines.append(f'#define AEFolder{i} "{v["folder"]}"')
open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("wrote", out, "confirmed" if cfg["confirmed"] else "NOT CONFIRMED")
